def summary() -> str:
    lines = []
    for p, title in [("A", "必须在贵方开发完成前对齐"),
                     ("B", "可省掉贵方工作量"),
                     ("C", "口径补充，避免联调分歧")]:
        items = [c for c in CHANGES if c["prio"] == p]
        lines.append(f"【{p}】{title}（{len(items)} 项）")
        for c in items:
            lines.append(f"  · {c['loc']} —— {c['what'][:40]}… [{c['impact']}]")
    return "\n".join(lines)


